/**
 * Ensures Surah name is never duplicated (e.g. fixes "سورة سورة البقرة" -> "سورة البقرة")
 */
export function formatSurahName(name: string, language: AppLanguage = 'ar'): string {
  if (!name) return '';
  const trimmed = name.trim();
  // Strip duplicate prefix if present
  if (trimmed.startsWith('سُورَةُ') || trimmed.startsWith('سورة')) {
    return trimmed;
  }
  return language === 'ar' ? `سورة ${trimmed}` : trimmed;
}

/**
 * Converts numbers into Eastern Arabic digits (١, ٢, ٣, ...)
 */
export function toArabicDigits(num: number | string): string {
  const arabicDigits = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
  return String(num)
    .replace(/[0-9]/g, (ch) => arabicDigits[Number(ch)] ?? ch);
}

